import { existsSync } from "node:fs";
import { join } from "node:path";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { COLOUR_ENVIRONMENTS, DELEGATED_COLOUR_ENVIRONMENTS } from "./colour-environments";
import type { Files } from "./workspace-parity-harness";
import { binary, Harness, nodeEntry, workspaceFiles } from "./workspace-parity-harness";

/**
 * `vis hook list` exists twice: the Node handler (`src/commands/hook/list.ts`) and the native fast path
 * (`native/cli/src/hook/list.rs`). For every hooks directory the native path accepts it must print the same text
 * with the same exit status as Node, and every shape it declines must be handed to Node before anything is printed
 * (see `workspace-parity-harness.ts` for how both are proved).
 */

const harness = new Harness(["hook", "list"]);

const STAGES = [
    "applypatch-msg",
    "commit-msg",
    "post-applypatch",
    "post-checkout",
    "post-commit",
    "post-merge",
    "post-rewrite",
    "pre-applypatch",
    "pre-auto-gc",
    "pre-commit",
    "pre-merge-commit",
    "pre-push",
    "pre-rebase",
    "prepare-commit-msg",
];

const hooks = (scripts: Record<string, string>, directory = ".vis/hooks"): Files => workspaceFiles(Object.fromEntries(Object.entries(scripts).map(([stage, content]) => [`${directory}/${stage}`, content])));

const MIGRATED = [
    "#!/usr/bin/env sh",
    "# Generated by vis hook migrate",
    "# NOTE: edit config.json",
    "set -e",
    "",
    "# lint: Lint the sources",
    "npx eslint .",
    "# format",
    "prettier --check .",
    "  --ignore-unknown",
    "# typecheck: Run tsc",
    "",
    "# a:b: Colon in the id",
    "echo one",
    "",
].join("\n");

describe.skipIf(!binary || process.platform === "win32" || !existsSync(nodeEntry))("vis hook list: native vs Node", () => {
    beforeAll(() => {
        harness.setup("vis-hook-list-parity-");
    });

    afterAll(() => {
        harness.teardown();
    });

    describe("accepted shapes", () => {
        it("says so when there is no hooks directory", () => {
            expect.hasAssertions();

            expect(harness.expectParity(workspaceFiles({}), []).stdout).toBe("No hooks installed in .vis/hooks/.\n");
        });

        it("says so when the hooks directory holds no stage script", () => {
            expect.hasAssertions();

            harness.expectParity(workspaceFiles({ ".vis/hooks/config.json": "{}\n", ".vis/hooks/README.md": "x\n" }), []);
            harness.expectParity(workspaceFiles({ ".vis/hooks/.keep": "" }), []);
        });

        it("lists every standard stage in the order Node sorts them", () => {
            expect.hasAssertions();

            const result = harness.expectParity(hooks(Object.fromEntries(STAGES.map((stage) => [stage, `# ${stage}: Stage\necho ${stage}\n`]))), []);

            expect(result.stdout.split("\n").filter((line) => /^\S.* \(\d+ lines\)$/.test(line))).toHaveLength(STAGES.length);
        });

        it("reads the blocks a migration writes", () => {
            expect.hasAssertions();

            const result = harness.expectParity(hooks({ "pre-commit": MIGRATED }), []);

            expect(result.stdout).toContain("  - lint — Lint the sources\n      npx eslint .\n");
            expect(result.stdout).toContain("  - a:b — Colon in the id\n");
        });

        it("treats a hand-written script as one custom block", () => {
            expect.hasAssertions();

            harness.expectParity(hooks({ "pre-push": "#!/bin/sh\nset -e\n\nnpm test\nnpm run lint\n" }), []);
            harness.expectParity(hooks({ "pre-push": "npm test" }), []);
        });

        it("counts the lines of an empty or blank script", () => {
            expect.hasAssertions();

            harness.expectParity(hooks({ "commit-msg": "", "post-commit": "\n", "post-merge": "set -e\n", "pre-commit": "\n\n\n", "pre-push": "#!/bin/sh\n" }), []);
            harness.expectParity(hooks({ "pre-commit": "   \n\t\n" }), []);
        });

        it("reads a header the way the JavaScript pattern does", () => {
            expect.hasAssertions();

            const lines = [
                "# id",
                "# id:",
                "# id: name",
                "# id:  two  spaces  ",
                "# id:\tname",
                "# id: ",
                "# id:  ",
                "# id:   ",
                "# a:b",
                "# a:b: c",
                "# a::b",
                "# a::",
                "# a:: x",
                "# :x",
                "#x",
                "# ",
                "#  x",
                "# a b",
                "# a:b c",
                "# #hash: name",
                "# Generated by x",
                "# NOTE: y",
                "#!shebang",
                "cmd",
            ];

            for (const line of lines) {
                harness.expectParity(hooks({ "pre-commit": `${line}\n` }), []);
                harness.expectParity(hooks({ "pre-commit": `${line}\nnext\n${line}` }), []);
            }
        });

        it("prints format characters and braces in a script and a name as they are", () => {
            expect.hasAssertions();

            const script = [
                "# fmt: Check %s and %d and %%",
                "printf '%s %d %%\\n' \"${x}\" {0} {name} %j %o %O %i %f %c",
                "# %s: Literal %",
                "echo 100% $((1+1)) ${a:-b} {{x}} %1$s",
                "",
            ].join("\n");

            const result = harness.expectParity(hooks({ "pre-commit": script, "pre-push": "%s\n%d\n" }), []);

            expect(result.stdout).toContain("%s %d %%");
        });

        it("shortens a first command line of more than 120 characters", () => {
            expect.hasAssertions();

            for (const length of [100, 119, 120, 121, 122, 200]) {
                const result = harness.expectParity(hooks({ "pre-commit": `# long: Long\n${"x".repeat(length)}\nsecond line\n` }), []);

                expect(result.stdout).toContain(length > 120 ? `${"x".repeat(117)}...` : "x".repeat(length));
            }
        });

        it("shows the first command line that is not blank", () => {
            expect.hasAssertions();

            harness.expectParity(hooks({ "pre-commit": "# a\n \t \nreal command\nmore\n# b\n   \n" }), []);
            harness.expectParity(hooks({ "pre-commit": "# a\n   \n\t\n" }), []);
        });

        it("skips what is not a standard stage script", () => {
            expect.hasAssertions();

            harness.expectParity(
                workspaceFiles({
                    ".vis/hooks/.hidden": "echo hidden\n",
                    ".vis/hooks/_/pre-commit": "echo dispatcher\n",
                    ".vis/hooks/config.json": "{}\n",
                    ".vis/hooks/pre-commit": "# kept\necho kept\n",
                    ".vis/hooks/pre-commit.bak": "echo backup\n",
                    ".vis/hooks/pre-push/inner": "echo a directory named like a stage\n",
                    ".vis/hooks/unknown-hook": "echo unknown\n",
                }),
                [],
            );
        });

        it("follows a symbolic link to a stage script", () => {
            expect.hasAssertions();

            harness.expectParity(workspaceFiles({ ".vis/hooks/pre-commit": { link: "shared" }, ".vis/hooks/shared": "# shared\necho shared\n" }), []);
        });

        it.each([["--hooks-dir", ".githooks"], ["--hooks-dir=.githooks"], ["--hooks-dir", "ci/git-hooks"], ["--hooks-dir=hooks_2.d"], ["--hooks-dir", "missing"], ["--hooks-dir", ".vis/hooks"]])(
            "reads the directory given as %s",
            (...flags: string[]) => {
                expect.hasAssertions();

                const files = { ...hooks({ "pre-commit": "# in-default\necho a\n" }), ...hooks({ "pre-commit": "# custom\necho b\n" }, ".githooks"), ...hooks({ "pre-push": "# nested\necho c\n" }, "ci/git-hooks"), ...hooks({ "pre-commit": "# dotted\necho d\n" }, "hooks_2.d") };

                harness.expectParity(files, flags);
            },
        );

        it.each(COLOUR_ENVIRONMENTS)("prints what Node does under %j", (...[environment]: Record<string, string>[]) => {
            expect.hasAssertions();

            harness.expectParity(hooks({ "pre-commit": MIGRATED, "pre-push": "npm test\n" }), [], environment);
            harness.expectParity(workspaceFiles({}), [], environment);
        });

        it("prints what Node does at any terminal width", () => {
            expect.hasAssertions();

            for (const columns of ["20", "40", "80", "200"]) {
                harness.expectParity(hooks({ "pre-commit": MIGRATED }), [], { COLUMNS: columns });
            }
        });

        it("ignores a package manager pin like Node does", () => {
            expect.hasAssertions();

            harness.expectParity(workspaceFiles({ ".vis/hooks/pre-commit": "# a\necho a\n" }, { packageManager: "npm@10.0.0" }), []);
        });
    });

    describe("shapes handed to Node", () => {
        it.each([
            [["--json"]],
            [["extra"]],
            [["--hooks-dir"]],
            [["--hooks-dir="]],
            [["--hooks-dir", "/abs"]],
            [["--hooks-dir", "a/../b"]],
            [["--hooks-dir", "a//b"]],
            [["--hooks-dir", "dir/"]],
            [["--hooks-dir", "."]],
            [["--hooks-dir", "123"]],
            [["--hooks-dir", "true"]],
            [["--hooks-dir", "a b"]],
            [["--hooks-dir", ".vis/hooks", "--hooks-dir", "x"]],
        ])("`hook list %s` is declined", (args: string[]) => {
            expect.hasAssertions();

            harness.expectDelegation(hooks({ "pre-commit": "# a\necho a\n" }), args);
        });

        it("a run outside CI is declined", () => {
            expect.hasAssertions();

            // Node prints a random, rate-limited tip outside CI; VIS_CLI_TEST keeps it out of the comparison.
            harness.expectDelegation(hooks({ "pre-commit": "# a\necho a\n" }), [], { VIS_CLI_TEST: "1" }, false);
        });

        it.each(DELEGATED_COLOUR_ENVIRONMENTS)("%j is declined", (environment) => {
            expect.hasAssertions();

            harness.expectDelegation(hooks({ "pre-commit": "# a\necho a\n" }), [], environment);
        });

        it.each([{ NODE_ENV: "test" }, { NODE_ENV: "debug" }, { DEBUG: "vis" }, { PAIL_LOG_LEVEL: "debug" }, { CEREBRO_OUTPUT_LEVEL: "4" }])("the output setting %j is declined", (environment) => {
            expect.hasAssertions();

            harness.expectDelegation(hooks({ "pre-commit": "# a\necho a\n" }), [], environment);
        });

        it("a script that is not plain ASCII is declined", () => {
            expect.hasAssertions();

            harness.expectDelegation(hooks({ "pre-commit": "# lint: Prüfen\necho ä\n" }), []);
            harness.expectDelegation(hooks({ "pre-commit": "﻿# lint\necho a\n" }), []);
            harness.expectDelegation(hooks({ "pre-commit": `# long\n${"ä".repeat(130)}\n` }), []);
        });

        it("a script with a carriage return, form feed or control character is declined", () => {
            expect.hasAssertions();

            harness.expectDelegation(hooks({ "pre-commit": "# lint: Lint\r\necho a\r\n" }), []);
            harness.expectDelegation(hooks({ "pre-commit": "# lint\f: x\necho a\n" }), []);
            harness.expectDelegation(hooks({ "pre-commit": "# lint\u000B\necho a\n" }), []);
            harness.expectDelegation(hooks({ "pre-commit": "echo \u0001\n" }), []);
        });

        it("a hooks directory that is a file is declined", () => {
            expect.hasAssertions();

            harness.expectDelegation(workspaceFiles({ ".vis/hooks": "not a directory\n" }), []);
        });

        it("a stage script that is a broken symbolic link is declined", () => {
            expect.hasAssertions();

            harness.expectDelegation(workspaceFiles({ ".vis/hooks/pre-commit": { link: "missing" } }), []);
        });

        it("a vis.config is declined", () => {
            expect.hasAssertions();

            harness.expectDelegation({ ...hooks({ "pre-commit": "# a\necho a\n" }), "vis.config.ts": "export default {};\n" }, []);
        });

        it("a workspace that is not rooted at the working directory is declined", () => {
            expect.hasAssertions();

            const [nodeRoot, nativeRoot] = harness.pair({ ...hooks({ "pre-commit": "# a\necho a\n" }), "packages/a/package.json": '{"name":"a"}\n' });
            const directory = "packages/a";

            expect(harness.runNative([], join(nativeRoot, directory)).status).toBe(70);
            expect(harness.runNode([], join(nodeRoot, directory)).status).toBe(0);
        });
    });
});
