import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import microUtilitiesManifest from "module-replacements/manifests/micro-utilities.json" with { type: "json" };
import nativeManifest from "module-replacements/manifests/native.json" with { type: "json" };
import preferredManifest from "module-replacements/manifests/preferred.json" with { type: "json" };
import { describe, expect, it } from "vitest";

import { buildNativeOptimizeTables, renderNativeOptimizeTables } from "../../src/commands/optimize/native-tables";

/**
 * The native `vis optimize` reads its replacement data from `native/cli/src/optimize-tables.json`, which is
 * generated by the functions the Node handler runs (`src/commands/optimize/replacements.ts`) over the installed
 * `module-replacements`, `module-replacements-codemods` and `@socketsecurity/registry` packages. A dependency bump
 * that changes what the handler reports fails here until the file is regenerated:
 * `VIS_UPDATE_OPTIMIZE_TABLES=1 pnpm exec vitest run __tests__/native/optimize-tables.test.ts`.
 */

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const tablesPath = join(packageRoot, "native", "cli", "src", "optimize-tables.json");

describe("native optimize tables", () => {
    it.runIf(process.env["VIS_UPDATE_OPTIMIZE_TABLES"] === "1")("regenerates the file when asked to", async () => {
        expect.assertions(1);

        writeFileSync(tablesPath, await renderNativeOptimizeTables());

        expect(readFileSync(tablesPath, "utf8")).toBe(await renderNativeOptimizeTables());
    });

    it("match the handler's data byte for byte", async () => {
        expect.assertions(1);

        expect(readFileSync(tablesPath, "utf8")).toBe(await renderNativeOptimizeTables());
    });

    it("hold a pinned spec for every socket override, and codemod flags only for e18e entries", async () => {
        expect.assertions(3);

        const { e18e, socket } = await buildNativeOptimizeTables();

        expect(socket.length).toBeGreaterThan(0);
        expect(socket.every(([, replacement, spec, pinned]) => spec.startsWith(`npm:${replacement}@^`) && pinned.startsWith(`npm:${replacement}@`))).toBe(true);
        expect(e18e.every(([category]) => ["micro-utility", "native", "preferred"].includes(category))).toBe(true);
    });

    it("hold one entry for every mapping of the module-replacements manifests", async () => {
        expect.assertions(2);

        const expected = [nativeManifest, preferredManifest, microUtilitiesManifest].reduce((sum, manifest) => sum + Object.keys(manifest.mappings).length, 0);

        const { e18e } = await buildNativeOptimizeTables();

        expect(expected).toBeGreaterThan(0);
        expect(e18e).toHaveLength(expected);
    });
});
