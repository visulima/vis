const ITERATIONS = 300;
const RNG_SEED = 1337;

// Deterministic Lehmer generator (MINSTD). Products stay below 2^53, so the sequence keeps its full period.
// A failing iteration replays from RNG_SEED and its index.
const createRandom = (seed: number): (() => number) => {
    let state = seed;

    return (): number => {
        state = (state * 48_271) % 2_147_483_647;

        return state / 2_147_483_647;
    };
};

