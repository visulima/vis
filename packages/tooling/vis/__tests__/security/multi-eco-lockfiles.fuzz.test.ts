const ALPHABET = `{}[]()"'\\:,=#%\n\r\t -./0123456789abcdefghijklmnopqrstuvwxyz\u0000\uFFFD`;

// Mutates a valid sample: a few deletes and inserts with a rare truncation, or pure noise about one time in ten.
// Truncation stays rare because a truncated JSON sample fails at parse time and never reaches the post-parse code.
const mutate = (sample: string, random: () => number): string => {
    if (random() < 0.1) {
        return Array.from({ length: Math.floor(random() * 256) }, () => String.fromCodePoint(Math.floor(random() * 2048))).join("");
    }

    let out = sample;
    const ops = 1 + Math.floor(random() * 4);

    for (let i = 0; i < ops; i++) {
        const position = Math.floor(random() * (out.length + 1));
        const kind = random();

        if (kind < 0.475) {
            out = out.slice(0, position) + out.slice(position + 1);
        } else if (kind < 0.95) {
            out = out.slice(0, position) + ALPHABET.charAt(Math.floor(random() * ALPHABET.length)) + out.slice(position);
        } else {
            out = out.slice(0, position);
        }
    }

    return out;
};

describe(lockedPackagesForEcosystem, () => {
    let root: string;

    beforeAll(() => {
        root = mkdtempSync(join(tmpdir(), "vis-lockfile-fuzz-"));
    });

    afterAll(() => {
        rmSync(root, { force: true, recursive: true });
    });

    it.each(Object.entries(SAMPLES))("parses the %s sample and survives mutated inputs without throwing", (file, { ecosystem, sample }) => {
        expect.assertions(2);

        const dir = mkdtempSync(join(root, "case-"));

        // Guard against a sample that silently stops parsing, which would make the fuzz loop vacuous.
        writeFileSync(join(dir, file), sample);

        expect(lockedPackagesForEcosystem(dir, ecosystem).length).toBeGreaterThan(0);

        const random = createRandom(RNG_SEED);
        const failures: string[] = [];

        for (let i = 0; i < ITERATIONS; i++) {
            const input = mutate(sample, random);

            writeFileSync(join(dir, file), input);

            try {
                const packages = lockedPackagesForEcosystem(dir, ecosystem);

                if (
                    !packages.every((pkg) => typeof pkg.name === "string" && typeof pkg.version === "string" && pkg.name.length > 0 && pkg.version.length > 0)
                ) {
                    failures.push(`iteration ${i}: malformed entry for input ${JSON.stringify(input)}`);
                }
            } catch (error) {
                failures.push(`iteration ${i}: ${String(error)} for input ${JSON.stringify(input)}`);
            }
        }

        expect({ count: failures.length, first: failures.slice(0, 5) }).toStrictEqual({ count: 0, first: [] });
    });
});
