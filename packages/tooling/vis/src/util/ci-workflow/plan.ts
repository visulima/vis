/**
 * Planning for `vis sync ci-workflow`: which targets run, in which order,
 * split into how many shards. The provider renderers only turn a plan into
 * YAML.
 *
 * Targets are layered by `dependsOn`: a target lands one group after the
 * latest listed target it reaches. Targets in one group run at the same time
 * (GitHub `parallel:` steps, GitLab jobs without `needs:` between them).
 */

import type { TargetDependencyConfig } from "@visulima/task-runner";

import type { CiWorkflowConfig } from "../../config/types/ci";
import { VisUserError } from "../../errors/vis-user-error";
import { CI_PACKAGE_MANAGER_COMMANDS } from "../../pm/ci-commands";
import type { LockfilePackageManager } from "../../preflight/lockfile";
import type { RuntimeTool } from "../../runtime/toolchain";
import { reachableFrom } from "../reachable";
import type { DetectedEcosystem } from "./ecosystems";

/** Targets used when `ci.workflow.targets` is unset, in this order, when present in the workspace. */
const DEFAULT_CI_TARGETS = ["lint", "typecheck", "lint:types", "build", "test"] as const;

export const GENERATED_NOTE = "Generated by `vis sync ci-workflow`. Do not edit by hand: change `ci.workflow` in vis.config.ts and re-run it.";

export interface CiWorkflowTarget {
    name: string;
    /** Number of `--partition` shards; 1 means unpartitioned. */
    shards: number;
}

export interface CiWorkflowPlan {
    /** Run affected projects (`vis ci`) instead of all projects (`vis run`). */
    affected: boolean;
    /** Branches whose pushes run the workflow (GitHub branch-filter globs). */
    branches: string[];
    /** `taskRunner.cacheDirectory` from the config, when set; it wins over `VIS_CACHE_DIRECTORY`. */
    cacheDirectory: string | undefined;
    /** Run `vis sync ci-workflow --check` in the workflow, so a stale workflow fails CI. */
    checkDrift: boolean;
    /** Non-JavaScript toolchains the workspace needs. */
    ecosystems: DetectedEcosystem[];
    /** Target groups, in order. Targets in one group do not depend on each other. */
    layers: CiWorkflowTarget[][];
    nodeVersion: string;
    /** The JavaScript package manager; `undefined` when the workspace has no JS lockfile and vis is installed on its own. */
    packageManager: LockfilePackageManager | undefined;
    /** Names of the files in the workspace root, for version files such as `.python-version` or `global.json`. */
    rootFiles: ReadonlySet<string>;
    runsOn: string;
    timeoutMinutes: number;
    /** Versions pinned in `toolchain.tools` (vis.config.ts); they win over version files and defaults. */
    toolchainPins: Partial<Record<RuntimeTool, string>>;
    /** The vis version installed when there is no JS package manager. */
    visVersion: string;
}

interface TargetLike {
    dependsOn?: ReadonlyArray<string | TargetDependencyConfig>;
}

type TargetEdges = ReadonlyMap<string, ReadonlySet<string>>;

/** Target name a `dependsOn` entry points at: `^build` and `build` both mean `build`. */
const dependencyTargetName = (entry: string | TargetDependencyConfig): string => {
    const name = typeof entry === "string" ? entry : entry.target;

    return name.startsWith("^") ? name.slice(1) : name;
};

/**
 * Target-level dependency edges: `test → build` when any project's `test`
 * (or the `tasks.test` default) lists `build` / `^build` in `dependsOn`.
 * A project's own target config wins over the default, as in the task graph.
 */
export const collectTargetDependencies = (
    projects: Record<string, { targets?: Record<string, TargetLike> }>,
    targetDefaults: Record<string, TargetLike | undefined> = {},
): Map<string, Set<string>> => {
    const edges = new Map<string, Set<string>>();

    for (const project of Object.values(projects)) {
        for (const [name, target] of Object.entries(project.targets ?? {})) {
            const set = edges.get(name) ?? new Set<string>();

            for (const entry of target.dependsOn ?? targetDefaults[name]?.dependsOn ?? []) {
                set.add(dependencyTargetName(entry));
            }

            edges.set(name, set);
        }
    }

    return edges;
};

/**
 * Returns `edges` plus a `target → build` edge for every listed target that
 * `dependsOn` does not already order relative to `build` (in either
 * direction), and the targets that gained one.
 */
export const withBuildFirst = (targets: ReadonlyArray<string>, edges: TargetEdges): { edges: Map<string, Set<string>>; ordered: string[] } => {
    const result = new Map([...edges].map(([name, dependencies]) => [name, new Set(dependencies)]));

    if (!targets.includes("build")) {
        return { edges: result, ordered: [] };
    }

    const reach = (from: string): Set<string> => reachableFrom([from], (node) => edges.get(node));
    const fromBuild = reach("build");
    const ordered = targets.filter((target) => target !== "build" && !reach(target).has("build") && !fromBuild.has(target));

    for (const target of ordered) {
        result.set(target, new Set([...(result.get(target) ?? []), "build"]));
    }

    return { edges: result, ordered };
};

/**
 * Orders `targets` into groups. A target lands one group after the latest
 * listed target it reaches through `dependsOn` (following unlisted targets in
 * between); targets that reach no other listed target share the first group.
 * A target reaching itself only means other projects run it first (`^test`),
 * which vis orders inside the step, so that is not a cycle. Throws on a cycle
 * between listed targets.
 */
export const layerTargets = (targets: ReadonlyArray<string>, edges: TargetEdges): string[][] => {
    const listed = new Set(targets);
    const dependsOnListed = new Map(
        targets.map((target) => [target, [...reachableFrom([target], (node) => edges.get(node))].filter((node) => listed.has(node) && node !== target)]),
    );
    const depth = new Map<string, number>();
    const visiting = new Set<string>();

    const depthOf = (target: string): number => {
        const known = depth.get(target);

        if (known !== undefined) {
            return known;
        }

        if (visiting.has(target)) {
            throw new VisUserError(`ci.workflow.targets: "${target}" depends on itself through dependsOn, so it cannot be ordered.`);
        }

        visiting.add(target);

        const value = Math.max(0, ...(dependsOnListed.get(target) ?? []).map((dependency) => depthOf(dependency) + 1));

        visiting.delete(target);
        depth.set(target, value);

        return value;
    };

    const layers: string[][] = [];

    for (const target of targets) {
        const index = depthOf(target);
        const layer = layers[index] ?? [];

        layer.push(target);
        layers[index] = layer;
    }

    return layers.filter((layer) => layer.length > 0);
};

/**
 * Resolves `ci.workflow` against the workspace into a plan. Rejects targets no
 * project defines and partitions that would otherwise be ignored silently
 * (a typo'd target name, a non-integer shard count).
 */
export const buildCiWorkflowPlan = ({
    cacheDirectory,
    defaultBase,
    ecosystems = [],
    packageManager,
    projects,
    rootFiles = new Set(),
    settings,
    targetDefaults,
    toolchainPins = {},
    visVersion,
}: {
    cacheDirectory: string | undefined;
    defaultBase: string | undefined;
    ecosystems?: DetectedEcosystem[];
    packageManager: LockfilePackageManager | undefined;
    projects: Record<string, { targets?: Record<string, TargetLike> }>;
    rootFiles?: ReadonlySet<string>;
    settings: CiWorkflowConfig;
    targetDefaults?: Record<string, TargetLike | undefined>;
    toolchainPins?: Partial<Record<RuntimeTool, string>>;
    visVersion: string;
}): { buildFirstOrdered: string[]; plan: CiWorkflowPlan } => {
    if (settings.timeoutMinutes !== undefined && (!Number.isInteger(settings.timeoutMinutes) || settings.timeoutMinutes < 1)) {
        throw new VisUserError(`ci.workflow.timeoutMinutes must be a positive integer, got ${JSON.stringify(settings.timeoutMinutes)}.`);
    }

    if (settings.targets?.length === 0) {
        throw new VisUserError("ci.workflow.targets is empty. List the targets to run, or remove it to use the defaults.");
    }

    const targetNames = new Set(Object.values(projects).flatMap((project) => Object.keys(project.targets ?? {})));
    const targets = settings.targets ?? DEFAULT_CI_TARGETS.filter((target) => targetNames.has(target));
    const unknownTargets = targets.filter((target) => !targetNames.has(target));

    if (unknownTargets.length > 0) {
        throw new VisUserError(`ci.workflow.targets: no project defines ${unknownTargets.map((target) => `"${target}"`).join(", ")}.`);
    }

    if (targets.length === 0) {
        throw new VisUserError(`No project defines any of ${DEFAULT_CI_TARGETS.join(", ")}. Set ci.workflow.targets in vis.config.ts.`);
    }

    const partitions = settings.partitions ?? {};
    const declaredEdges = collectTargetDependencies(projects, targetDefaults);

    for (const [target, shards] of Object.entries(partitions)) {
        if (!targets.includes(target)) {
            throw new VisUserError(`ci.workflow.partitions.${target}: "${target}" is not one of the workflow's targets (${targets.join(", ")}).`);
        }

        if (!Number.isInteger(shards) || shards < 1) {
            throw new VisUserError(`ci.workflow.partitions.${target} must be a positive integer, got ${JSON.stringify(shards)}.`);
        }

        // Shards run at the same time, so a shard cannot wait for another shard's tasks.
        if (shards > 1 && declaredEdges.get(target)?.has(target)) {
            throw new VisUserError(
                `ci.workflow.partitions.${target}: ${target} depends on ${target} of other projects (^${target}), so its shards would depend on each other. Remove the partition.`,
            );
        }
    }

    let edges = declaredEdges;
    let buildFirstOrdered: string[] = [];

    if (settings.buildFirst ?? true) {
        ({ edges, ordered: buildFirstOrdered } = withBuildFirst(targets, edges));
    }

    return {
        buildFirstOrdered,
        plan: {
            affected: settings.affected ?? true,
            branches: settings.branches ?? [defaultBase ?? "main"],
            cacheDirectory,
            checkDrift: settings.checkDrift ?? true,
            ecosystems,
            layers: layerTargets(targets, edges).map((layer) => layer.map((name) => { return { name, shards: partitions[name] ?? 1 }; })),
            nodeVersion: settings.nodeVersion ?? toolchainPins.node ?? "22",
            packageManager,
            rootFiles,
            runsOn: settings.runsOn ?? "ubuntu-latest",
            timeoutMinutes: settings.timeoutMinutes ?? 60,
            toolchainPins,
            visVersion,
        },
    };
};

/**
 * The `vis` invocation for one target. `vis ci` already resolves the affected
 * base/head from the CI environment; `--no-install` because the workflow
 * installed once up front.
 */
/** Quotes a target name for the shell when it holds anything beyond name characters. */
const shellWord = (value: string): string => (/^[\w.:@/+-]+$/u.test(value) ? value : `'${value.replaceAll("'", String.raw`'\''`)}'`);

/** How the workflow runs vis: through the JS package manager, or the globally installed `vis`. */
export const visCommand = (plan: CiWorkflowPlan): string =>
    (plan.packageManager === undefined ? "vis" : `${CI_PACKAGE_MANAGER_COMMANDS[plan.packageManager].exec} vis`);

/** Installs vis on its own, for a workspace without a JS package manager. */
export const visInstallCommand = (plan: CiWorkflowPlan): string => `npm install --global @visulima/vis@${plan.visVersion}`;

export const visTargetCommand = (plan: CiWorkflowPlan, target: string, flags: ReadonlyArray<string>): string => {
    const vis = visCommand(plan);
    const base = plan.affected ? `${vis} ci ${shellWord(target)} --no-install` : `${vis} run ${shellWord(target)}`;

    return [base, ...flags, "--if-present"].join(" ");
};

/** Quotes a scalar for YAML: a JSON string is a valid double-quoted YAML scalar. */
export const yamlString = (value: string): string => JSON.stringify(value);
