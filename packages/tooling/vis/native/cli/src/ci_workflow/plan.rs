//! Planning for `vis sync ci-workflow`: which targets run, in which order, split into how many
//! shards (`src/util/ci-workflow/plan.ts`). The provider renderers only turn a plan into YAML.
//!
//! Every input the Node planner rejects with an error (an unknown target, a bad partition, a cycle)
//! returns `None` here, so the run goes to Node and prints Node's message.

use std::collections::{BTreeMap, BTreeSet, VecDeque};

use super::config::Settings;
use super::ecosystems::Detected;
use super::github::RunStep;
use super::yaml::Yaml;

/// Targets used when `ci.workflow.targets` is unset, in this order, when present in the workspace.
const DEFAULT_CI_TARGETS: [&str; 5] = ["lint", "typecheck", "lint:types", "build", "test"];

pub const GENERATED_NOTE: &str =
    "Generated by `vis sync ci-workflow`. Do not edit by hand: change `ci.workflow` in vis.config.ts and re-run it.";

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub enum Provider {
    Github,
    Gitlab,
}

impl Provider {
    pub fn parse(name: &str) -> Option<Provider> {
        match name {
            "github" => Some(Provider::Github),
            "gitlab" => Some(Provider::Gitlab),
            _ => None,
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Provider::Github => "github",
            Provider::Gitlab => "gitlab",
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct Target {
    /// Environment variables from the target's object form in `ci.workflow.targets`.
    pub env: Option<Vec<(String, String)>>,
    pub name: String,
    /// Number of `--partition` shards; 1 means unpartitioned.
    pub shards: u64,
}

#[derive(Clone, Debug)]
pub struct Plan {
    pub affected: bool,
    pub branches: Vec<String>,
    pub cache_directory: Option<String>,
    pub check_drift: bool,
    pub ecosystems: Vec<Detected>,
    pub github_after: Vec<RunStep>,
    pub github_after_setup: Vec<RunStep>,
    pub github_env: Option<Yaml>,
    pub github_permissions: Vec<(String, String)>,
    pub github_services: Option<Yaml>,
    pub gitlab_after_script: Option<Yaml>,
    pub gitlab_before_script: Vec<String>,
    pub gitlab_image: Option<String>,
    pub gitlab_services: Option<Yaml>,
    pub gitlab_stage: Option<String>,
    pub gitlab_tags: Option<Yaml>,
    pub gitlab_variables: Vec<(String, String)>,
    /// Target groups, in order. Targets in one group do not depend on each other.
    pub layers: Vec<Vec<Target>>,
    pub node_version: String,
    /// The JavaScript package manager's name as `ci-tables.json` keys it.
    pub package_manager: String,
    /// Providers the files are generated for, sorted.
    pub providers: Vec<Provider>,
    /// Names of the files in the workspace root, for version files such as `.python-version`.
    pub root_files: BTreeSet<String>,
    pub runs_on: String,
    pub timeout_minutes: u64,
    /// Versions pinned in `toolchain.tools`.
    pub toolchain_pins: BTreeMap<String, String>,
}

impl Plan {
    pub fn pin(&self, tool: &str) -> Option<&str> {
        self.toolchain_pins.get(tool).map(String::as_str)
    }
}

type Edges = BTreeMap<String, BTreeSet<String>>;

/// Target-level dependency edges: `test → build` when a project's `test` (or the `tasks.test` default)
/// lists `build` / `^build` in `dependsOn`. A name has an entry when some project defines the target.
pub fn collect_target_dependencies(target_names: &BTreeSet<String>, defaults: &BTreeMap<String, Vec<String>>) -> Edges {
    target_names
        .iter()
        .map(|name| (name.clone(), defaults.get(name).map(|names| names.iter().cloned().collect()).unwrap_or_default()))
        .collect()
}

/// Every node reachable from `starts` by following one or more edges. A start node is included only
/// when a cycle leads back to it.
fn reachable_from(starts: &[&str], edges: &Edges) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    let mut queue: VecDeque<String> = VecDeque::new();

    for start in starts {
        queue.extend(edges.get(*start).into_iter().flatten().cloned());
    }

    while let Some(node) = queue.pop_front() {
        if found.insert(node.clone()) {
            queue.extend(edges.get(&node).into_iter().flatten().cloned());
        }
    }

    found
}

/// `edges` plus a `target → build` edge for every listed target that `dependsOn` does not already order
/// relative to `build` (in either direction), and the targets that gained one.
pub fn with_build_first(targets: &[String], edges: &Edges) -> (Edges, Vec<String>) {
    let mut result = edges.clone();

    if !targets.iter().any(|target| target == "build") {
        return (result, Vec::new());
    }

    let from_build = reachable_from(&["build"], edges);
    let ordered: Vec<String> = targets
        .iter()
        .filter(|target| {
            target.as_str() != "build"
                && !reachable_from(&[target.as_str()], edges).contains("build")
                && !from_build.contains(*target)
        })
        .cloned()
        .collect();

    for target in &ordered {
        result.entry(target.clone()).or_default().insert("build".to_owned());
    }

    (result, ordered)
}

/// Orders `targets` into groups. A target lands one group after the latest listed target it reaches
/// through `dependsOn` (following unlisted targets in between); targets that reach no other listed
/// target share the first group. A target reaching itself only means other projects run it first
/// (`^test`), which vis orders inside the step. `None` on a cycle between listed targets.
pub fn layer_targets(targets: &[String], edges: &Edges) -> Option<Vec<Vec<String>>> {
    let listed: BTreeSet<&str> = targets.iter().map(String::as_str).collect();
    let depends_on_listed: BTreeMap<&str, Vec<String>> = targets
        .iter()
        .map(|target| {
            let reached = reachable_from(&[target.as_str()], edges);

            (
                target.as_str(),
                reached.into_iter().filter(|node| listed.contains(node.as_str()) && node != target).collect(),
            )
        })
        .collect();
    let mut depth: BTreeMap<String, usize> = BTreeMap::new();
    let mut layers: Vec<Vec<String>> = Vec::new();

    fn depth_of(
        target: &str,
        depends_on_listed: &BTreeMap<&str, Vec<String>>,
        depth: &mut BTreeMap<String, usize>,
        visiting: &mut BTreeSet<String>,
    ) -> Option<usize> {
        if let Some(known) = depth.get(target) {
            return Some(*known);
        }

        if !visiting.insert(target.to_owned()) {
            return None;
        }

        let mut value = 0;

        for dependency in depends_on_listed.get(target).into_iter().flatten() {
            value = value.max(depth_of(dependency, depends_on_listed, depth, visiting)? + 1);
        }

        visiting.remove(target);
        depth.insert(target.to_owned(), value);

        Some(value)
    }

    for target in targets {
        let index = depth_of(target, &depends_on_listed, &mut depth, &mut BTreeSet::new())?;

        if layers.len() <= index {
            layers.resize(index + 1, Vec::new());
        }

        layers[index].push(target.clone());
    }

    Some(layers.into_iter().filter(|layer| !layer.is_empty()).collect())
}

/// What the planner needs from the workspace.
pub struct Workspace {
    pub cache_directory: Option<String>,
    pub default_base: Option<String>,
    pub ecosystems: Vec<Detected>,
    pub package_manager: String,
    pub root_files: BTreeSet<String>,
    /// Names of every target any project defines.
    pub target_names: BTreeSet<String>,
    /// `dependsOn` target names of each `tasks` default.
    pub task_depends_on: BTreeMap<String, Vec<String>>,
    pub toolchain_pins: BTreeMap<String, String>,
}

/// Resolves `ci.workflow` against the workspace into a plan, and the targets that were ordered after
/// `build` by `buildFirst`. `None` where the Node planner raises an error.
pub fn build_plan(workspace: Workspace, providers: &[Provider], settings: &Settings) -> Option<(Vec<String>, Plan)> {
    if settings.targets.as_ref().is_some_and(Vec::is_empty) {
        return None;
    }

    let targets: Vec<String> = match &settings.targets {
        None => DEFAULT_CI_TARGETS
            .iter()
            .filter(|target| workspace.target_names.contains(**target))
            .map(|target| (*target).to_owned())
            .collect(),
        Some(configured) => configured.iter().map(|target| target.name.clone()).collect(),
    };
    let target_env: BTreeMap<&str, &Option<Vec<(String, String)>>> =
        settings.targets.iter().flatten().map(|target| (target.name.as_str(), &target.env)).collect();

    if targets.iter().enumerate().any(|(index, target)| targets.iter().position(|other| other == target) != Some(index))
    {
        return None;
    }

    for steps in [&settings.github.after_setup, &settings.github.after] {
        if steps.iter().any(|step| step.run.is_some() == step.uses.is_some()) {
            return None;
        }
    }

    if targets.iter().any(|target| !workspace.target_names.contains(target)) || targets.is_empty() {
        return None;
    }

    let declared = collect_target_dependencies(&workspace.target_names, &workspace.task_depends_on);

    for (target, shards) in &settings.partitions {
        if !targets.contains(target) {
            return None;
        }

        // Shards run at the same time, so a shard cannot wait for another shard's tasks.
        if *shards > 1 && reachable_from(&[target.as_str()], &declared).contains(target) {
            return None;
        }
    }

    let mut edges = declared;
    let mut build_first_ordered = Vec::new();

    if settings.build_first.unwrap_or(true) {
        (edges, build_first_ordered) = with_build_first(&targets, &edges);
    }

    let layers = layer_targets(&targets, &edges)?
        .into_iter()
        .map(|layer| {
            layer
                .into_iter()
                .map(|name| Target {
                    env: target_env.get(name.as_str()).and_then(|env| (*env).clone()),
                    shards: settings
                        .partitions
                        .iter()
                        .find(|(partitioned, _)| *partitioned == name)
                        .map_or(1, |(_, shards)| *shards),
                    name,
                })
                .collect()
        })
        .collect();
    let mut sorted_providers = providers.to_vec();

    sorted_providers.sort();

    let node_version = settings
        .node_version
        .clone()
        .or_else(|| workspace.toolchain_pins.get("node").cloned())
        .unwrap_or_else(|| "22".to_owned());

    Some((
        build_first_ordered,
        Plan {
            affected: settings.affected.unwrap_or(true),
            branches: settings
                .branches
                .clone()
                .unwrap_or_else(|| vec![workspace.default_base.clone().unwrap_or_else(|| "main".to_owned())]),
            cache_directory: workspace.cache_directory,
            check_drift: settings.check_drift.unwrap_or(true),
            ecosystems: workspace.ecosystems,
            github_after: settings.github.after.clone(),
            github_after_setup: settings.github.after_setup.clone(),
            github_env: settings.github.env.clone(),
            github_permissions: settings.github.permissions.clone(),
            github_services: settings.github.services.clone(),
            gitlab_after_script: settings.gitlab.after_script.clone(),
            gitlab_before_script: settings.gitlab.before_script.clone(),
            gitlab_image: settings.gitlab.image.clone(),
            gitlab_services: settings.gitlab.services.clone(),
            gitlab_stage: settings.gitlab.stage.clone(),
            gitlab_tags: settings.gitlab.tags.clone(),
            gitlab_variables: settings.gitlab.variables.clone(),
            layers,
            node_version,
            package_manager: workspace.package_manager,
            providers: sorted_providers,
            root_files: workspace.root_files,
            runs_on: settings.runs_on.clone().unwrap_or_else(|| "ubuntu-latest".to_owned()),
            timeout_minutes: settings.timeout_minutes.unwrap_or(60),
            toolchain_pins: workspace.toolchain_pins,
        },
    ))
}

/// Quotes a target name for the shell when it holds anything beyond name characters
/// (`/^[\w.:@/+-]+$/u`, with `\w` ASCII only).
fn shell_word(value: &str) -> String {
    let plain = !value.is_empty()
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'.' | b':' | b'@' | b'/' | b'+' | b'-'));

    if plain {
        value.to_owned()
    } else {
        format!("'{}'", value.replace('\'', "'\\''"))
    }
}

/// The drift check, limited to the providers the files were generated for. `exec` is the package
/// manager's prefix for running a workspace binary (`pnpm exec`).
pub fn vis_drift_check_command(plan: &Plan, exec: &str) -> String {
    let providers: Vec<&str> = plan.providers.iter().map(|provider| provider.name()).collect();

    format!("{exec} vis sync ci-workflow --check --provider={}", providers.join(","))
}

/// The `vis` invocation for one target.
pub fn vis_target_command(plan: &Plan, exec: &str, target: &str, flags: &[String]) -> String {
    target_command(plan, exec, &shell_word(target), flags)
}

/// One command that builds the dependencies of every target (`vis run a,b --deps-only`), so a dependency
/// that several targets share runs once, even with caching disabled. Each name is quoted on its own: the
/// shell joins the pieces around the commas into one word.
pub fn vis_dependencies_command(plan: &Plan, exec: &str, targets: &[&str]) -> String {
    target_command(plan, exec, &target_list_word(targets), &["--deps-only".to_owned()])
}

fn target_list_word(targets: &[&str]) -> String {
    targets.iter().map(|target| shell_word(target)).collect::<Vec<_>>().join(",")
}

/// `word` is the shell word that names the target, or the comma-separated list of targets.
fn target_command(plan: &Plan, exec: &str, word: &str, flags: &[String]) -> String {
    let vis = format!("{exec} vis");
    let base = if plan.affected { format!("{vis} ci {word} --no-install") } else { format!("{vis} run {word}") };
    let mut parts = vec![base];

    parts.extend(flags.iter().cloned());
    parts.push("--if-present".to_owned());

    parts.join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn edges(pairs: &[(&str, &[&str])]) -> Edges {
        pairs
            .iter()
            .map(|(name, deps)| ((*name).to_owned(), deps.iter().map(|dep| (*dep).to_owned()).collect()))
            .collect()
    }

    fn names(list: &[&str]) -> Vec<String> {
        list.iter().map(|name| (*name).to_owned()).collect()
    }

    #[test]
    fn a_target_list_is_one_comma_joined_word_with_each_name_quoted_on_its_own() {
        assert_eq!(target_list_word(&["lint", "build", "test"]), "lint,build,test");
        assert_eq!(target_list_word(&["a b", "test"]), "'a b',test");
        assert_eq!(target_list_word(&["test"]), "test");
    }

    #[test]
    fn independent_targets_share_a_group_and_dependents_follow() {
        assert_eq!(
            layer_targets(&names(&["lint", "build", "test"]), &edges(&[("test", &["build"])])),
            Some(vec![names(&["lint", "build"]), names(&["test"])])
        );
    }

    #[test]
    fn unlisted_targets_in_between_are_followed() {
        let graph = edges(&[("bundle", &["build"]), ("e2e", &["bundle"])]);

        assert_eq!(layer_targets(&names(&["e2e", "build"]), &graph), Some(vec![names(&["build"]), names(&["e2e"])]));
    }

    #[test]
    fn a_target_reaching_itself_is_not_a_cycle_but_two_targets_are() {
        assert_eq!(layer_targets(&names(&["test"]), &edges(&[("test", &["test"])])), Some(vec![names(&["test"])]));
        assert_eq!(layer_targets(&names(&["a", "b"]), &edges(&[("a", &["b"]), ("b", &["a"])])), None);
    }

    #[test]
    fn build_goes_first_unless_dependson_already_orders_it() {
        let declared = edges(&[("build", &["codegen"])]);
        let targets = names(&["lint", "codegen", "build", "test"]);
        let (with, ordered) = with_build_first(&targets, &declared);

        assert_eq!(ordered, names(&["lint", "test"]));
        assert_eq!(
            layer_targets(&targets, &with),
            Some(vec![names(&["codegen"]), names(&["build"]), names(&["lint", "test"])])
        );
        assert_eq!(declared.keys().collect::<Vec<_>>(), ["build"]);
    }

    #[test]
    fn target_names_are_shell_quoted_unless_plain() {
        assert_eq!(shell_word("lint:types"), "lint:types");
        assert_eq!(shell_word("a b"), "'a b'");
        assert_eq!(shell_word("it's"), "'it'\\''s'");
        assert_eq!(shell_word("é"), "'é'");
    }
}
